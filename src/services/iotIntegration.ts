interface IoTSensor {
  id: string;
  type: 'air_quality' | 'noise_level' | 'traffic_flow' | 'water_level' | 'waste_bin' | 'street_light' | 'weather' | 'parking' | 'crowd_density';
  name: string;
  location: {
    lat: number;
    lng: number;
    address: string;
    zone: string;
  };
  status: 'active' | 'inactive' | 'maintenance' | 'error';
  lastReading: Date;
  batteryLevel?: number;
  signalStrength: number;
  manufacturer: string;
  model: string;
  installDate: Date;
  calibrationDate?: Date;
  thresholds: {
    warning: number;
    critical: number;
    unit: string;
  };
}

interface SensorReading {
  sensorId: string;
  timestamp: Date;
  value: number;
  unit: string;
  quality: 'good' | 'fair' | 'poor';
  metadata?: {
    temperature?: number;
    humidity?: number;
    batteryLevel?: number;
    rssi?: number;
  };
}

interface IoTAlert {
  id: string;
  sensorId: string;
  sensor: IoTSensor;
  type: 'threshold_exceeded' | 'sensor_offline' | 'low_battery' | 'maintenance_required' | 'anomaly_detected';
  severity: 'low' | 'medium' | 'high' | 'critical';
  title: string;
  description: string;
  reading?: SensorReading;
  createdAt: Date;
  resolvedAt?: Date;
  autoGenerated: boolean;
  reportId?: string; // If automatically created a civic report
}


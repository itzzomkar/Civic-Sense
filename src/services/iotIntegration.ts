  private mapSensorTypeToCategory(sensorType: string): string {
    const mapping = {
      'air_quality': 'Infrastructure',
      'noise_level': 'Other',
      'traffic_flow': 'Traffic',
      'waste_bin': 'Waste Management',
      'street_light': 'Lighting',
      'water_level': 'Water & Utilities',
      'weather': 'Other',
      'parking': 'Traffic',
      'crowd_density': 'Other'
    };
    return mapping[sensorType] || 'Other';
  }

  public getSensors(): IoTSensor[] {
    return Array.from(this.sensors.values());
  }

  public getSensor(sensorId: string): IoTSensor | undefined {
    return this.sensors.get(sensorId);
  }

  public getSensorReadings(sensorId: string, limit: number = 100): SensorReading[] {
    const readings = this.readings.get(sensorId) || [];
    return readings.slice(-limit);
  }

  public getAlerts(resolved: boolean = false): IoTAlert[] {
    return this.alerts.filter(alert => resolved ? alert.resolvedAt : !alert.resolvedAt);
  }

  public resolveAlert(alertId: string): boolean {
    const alert = this.alerts.find(a => a.id === alertId);
    if (alert && !alert.resolvedAt) {
      alert.resolvedAt = new Date();
      return true;
    }
    return false;
  }

  public getSmartCityDashboard(): SmartCityDashboard {
    const airQualityReadings = this.getLatestReadingsByType('air_quality');
    const noiseReadings = this.getLatestReadingsByType('noise_level');
    const trafficReadings = this.getLatestReadingsByType('traffic_flow');
    const wasteReadings = this.getLatestReadingsByType('waste_bin');
    const lightReadings = this.getLatestReadingsByType('street_light');
    const waterReadings = this.getLatestReadingsByType('water_level');

    const sensorStats = this.getSensorHealthStats();

    return {
      airQualityIndex: this.calculateAverage(airQualityReadings),
      noiseLevel: this.calculateAverage(noiseReadings),
      trafficFlow: this.calculateAverage(trafficReadings),
      waterLevels: waterReadings,
      wasteCapacity: this.calculateAverage(wasteReadings),
      streetLightStatus: this.calculateAverage(lightReadings),
      weatherData: {
        temperature: 28.5 + Math.random() * 5,
        humidity: 65 + Math.random() * 15,
        windSpeed: 5 + Math.random() * 10,
        rainfall: Math.random() * 2
      },
      alerts: this.getAlerts().slice(0, 10),
      sensorHealth: sensorStats
    };
  }

  private getLatestReadingsByType(sensorType: string): number[] {
    const sensorsOfType = Array.from(this.sensors.values()).filter(s => s.type === sensorType);
    return sensorsOfType.map(sensor => {
      const readings = this.readings.get(sensor.id) || [];
      const latest = readings[readings.length - 1];
      return latest ? latest.value : 0;
    });
  }

  private calculateAverage(values: number[]): number {
    if (values.length === 0) return 0;
    return values.reduce((sum, val) => sum + val, 0) / values.length;
  }

  private getSensorHealthStats() {
    const sensors = Array.from(this.sensors.values());
    const stats = {
      active: sensors.filter(s => s.status === 'active').length,
      inactive: sensors.filter(s => s.status === 'inactive').length,
      maintenance: sensors.filter(s => s.status === 'maintenance').length,
      total: sensors.length
    };
    return stats;
  }


  private startDataSimulation() {
    // Simulate real-time sensor data
    setInterval(() => {
      this.simulateSensorReadings();
    }, 30000); // Every 30 seconds

    // Check for alerts
    setInterval(() => {
      this.checkAlerts();
    }, 60000); // Every minute
  }

  private simulateSensorReadings() {
    this.sensors.forEach((sensor, sensorId) => {
      if (sensor.status === 'active') {
        const reading = this.generateMockReading(sensor);
        this.addSensorReading(sensorId, reading);
      }
    });
  }

  private generateMockReading(sensor: IoTSensor): SensorReading {
    const now = new Date();
    let value: number;
    let quality: 'good' | 'fair' | 'poor' = 'good';

    // Generate realistic values based on sensor type
    switch (sensor.type) {
      case 'air_quality':
        value = 80 + Math.random() * 60 + (Math.sin(Date.now() / 10000) * 20); // 80-140 AQI
        if (value > 150) quality = 'poor';
        else if (value > 100) quality = 'fair';
        break;

      case 'noise_level':
        value = 60 + Math.random() * 25 + (Math.sin(Date.now() / 5000) * 10); // 60-85 dB
        if (value > 80) quality = 'poor';
        else if (value > 70) quality = 'fair';
        break;

      case 'traffic_flow':
        const hour = now.getHours();
        const baseTraffic = hour >= 8 && hour <= 10 || hour >= 17 && hour <= 19 ? 600 : 200;
        value = baseTraffic + Math.random() * 200; // Rush hour vs normal
        break;

      case 'waste_bin':
        value = Math.min(100, (sensor.lastReading ? 75 : 50) + Math.random() * 15); // Gradual fill
        if (value > 90) quality = 'poor';
        else if (value > 80) quality = 'fair';
        break;

      case 'street_light':
        value = Math.random() > 0.95 ? 0 : 100; // Occasional outage
        break;

      case 'water_level':
        value = 82 + Math.random() * 10 + Math.sin(Date.now() / 20000) * 5; // 82-92%
        break;

      default:
        value = Math.random() * 100;
    }

    return {
      sensorId: sensor.id,
      timestamp: now,
      value: Math.round(value * 100) / 100,
      unit: sensor.thresholds.unit,
      quality,
      metadata: {
        temperature: 25 + Math.random() * 10,
        humidity: 60 + Math.random() * 20,
        batteryLevel: sensor.batteryLevel,
        rssi: sensor.signalStrength
      }
    };
  }

  public addSensorReading(sensorId: string, reading: SensorReading) {
    const readings = this.readings.get(sensorId) || [];
    readings.push(reading);
    
    // Keep only last 1000 readings per sensor
    if (readings.length > 1000) {
      readings.splice(0, readings.length - 1000);
    }
    
    this.readings.set(sensorId, readings);
    
    // Update sensor last reading time
    const sensor = this.sensors.get(sensorId);
    if (sensor) {
      sensor.lastReading = reading.timestamp;
    }
  }

  private checkAlerts() {
    this.sensors.forEach((sensor, sensorId) => {
      const readings = this.readings.get(sensorId) || [];
      const latestReading = readings[readings.length - 1];
      
      if (!latestReading) return;

      // Check threshold alerts
      if (latestReading.value >= sensor.thresholds.critical) {
        this.createAlert(sensor, 'threshold_exceeded', 'critical', latestReading);
      } else if (latestReading.value >= sensor.thresholds.warning) {
        this.createAlert(sensor, 'threshold_exceeded', 'high', latestReading);
      }

      // Check sensor health alerts
      const timeSinceLastReading = Date.now() - sensor.lastReading.getTime();
      if (timeSinceLastReading > 10 * 60 * 1000) { // 10 minutes
        this.createAlert(sensor, 'sensor_offline', 'medium');
      }

      // Check battery alerts
      if (sensor.batteryLevel && sensor.batteryLevel < 20) {
        this.createAlert(sensor, 'low_battery', 'medium');
      }

      // Check maintenance alerts
      if (sensor.calibrationDate) {
        const daysSinceCalibration = (Date.now() - sensor.calibrationDate.getTime()) / (1000 * 60 * 60 * 24);
        if (daysSinceCalibration > 90) {
          this.createAlert(sensor, 'maintenance_required', 'low');
        }
      }
    });
  }

  private createAlert(sensor: IoTSensor, type: IoTAlert['type'], severity: IoTAlert['severity'], reading?: SensorReading) {
    // Check if similar alert already exists
    const existingAlert = this.alerts.find(alert => 
      alert.sensorId === sensor.id && 
      alert.type === type && 
      !alert.resolvedAt
    );

    if (existingAlert) return; // Don't create duplicate alerts

    const alertTitles = {
      'threshold_exceeded': `${sensor.name} - Threshold Exceeded`,
      'sensor_offline': `${sensor.name} - Sensor Offline`,
      'low_battery': `${sensor.name} - Low Battery`,
      'maintenance_required': `${sensor.name} - Maintenance Required`,
      'anomaly_detected': `${sensor.name} - Anomaly Detected`
    };

    const alertDescriptions = {
      'threshold_exceeded': `${sensor.type.replace('_', ' ')} reading of ${reading?.value}${reading?.unit} exceeds ${severity === 'critical' ? 'critical' : 'warning'} threshold`,
      'sensor_offline': `Sensor has not reported data for over 10 minutes`,
      'low_battery': `Battery level is ${sensor.batteryLevel}%`,
      'maintenance_required': `Sensor requires calibration - last calibrated over 90 days ago`,
      'anomaly_detected': `Unusual reading pattern detected`
    };

    const alert: IoTAlert = {
      id: `alert_${Date.now()}_${sensor.id}`,
      sensorId: sensor.id,
      sensor,
      type,
      severity,
      title: alertTitles[type],
      description: alertDescriptions[type],
      reading,
      createdAt: new Date(),
      autoGenerated: true
    };

    this.alerts.push(alert);

    // Auto-generate civic report for critical issues
    if (severity === 'critical' && type === 'threshold_exceeded') {
      this.autoGenerateCivicReport(alert);
    }

    console.log(`IoT Alert: ${alert.title} - ${alert.description}`);
  }

